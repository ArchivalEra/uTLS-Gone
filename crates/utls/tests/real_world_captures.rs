/// 从一条转储里摘出**长度自洽**的那条握手记录的 ClientHello。
///
/// 与 `utls_testdata.rs` 的 `flow_client_hello` 同一套逻辑：内容类型 0x16 且
/// 长度恰好吃掉剩余字节的那条记录。curl 那条转储里 hello 之后还有 CCS 与
/// 应用数据帧，所以不能直接取第一条。
fn hello_of(dump: &[u8]) -> &[u8] {
    let mut i = 0usize;
    while i + 5 <= dump.len() {
        let rec_len = u16::from_be_bytes([dump[i + 3], dump[i + 4]]) as usize;
        if i + 5 + rec_len > dump.len() {
            break;
        }
        // 自洽判据：这条 0x16 记录的长度恰好 = 里面的握手消息（4 字节头 + 体）。
        // curl 转储里 hello 之后还有 CCS / 应用数据帧，所以「到转储末尾」不是判据。
        if dump[i] == 0x16 {
            let hs = &dump[i + 5..i + 5 + rec_len];
            let hs_len = ((hs[1] as usize) << 16) | ((hs[2] as usize) << 8) | hs[3] as usize;
            if 4 + hs_len == rec_len {
                return hs;
            }
        }
        i += 5 + rec_len;
    }
    panic!("转储里没找到长度自洽的握手记录");
}

/// 线上扩展条数（`u16 类型 + u16 长度 + 体` 逐条数一遍）。
fn wire_ext_count(hello: &[u8]) -> usize {
    let mut p = 4 + 2 + 32;
    p += 1 + hello[p] as usize;
    let cs = u16::from_be_bytes([hello[p], hello[p + 1]]) as usize;
    p += 2 + cs;
    p += 1 + hello[p] as usize;
    let n = u16::from_be_bytes([hello[p], hello[p + 1]]) as usize;
    p += 2;
    let region = &hello[p..p + n];
    let mut count = 0usize;
    let mut q = 0usize;
    while q + 4 <= region.len() {
        let bl = u16::from_be_bytes([region[q + 2], region[q + 3]]) as usize;
        q += 4 + bl;
        count += 1;
    }
    assert_eq!(q, region.len(), "扩展区长度字段与实际不符");
    count
}

/// **KeepPSK**：捕获里的 `pre_shared_key`（类型 41）不许被丢掉 ——
/// 上游只断言「spec 里有 PSK 扩展」，我们更强：它是**建模过的** `PreSharedKey`
/// （1 个 identity + 1 个 binder，与捕获一致），并且整条 hello **逐字节回放**。
#[test]
fn slack_capture_keeps_its_psk_extension_and_replays_byte_for_byte() {
    let hello = hello_of(SLACK_RECORD);
    let spec = ClientHelloSpec::from_bytes(hello).expect("反解");
    let psk = spec
        .extensions
        .iter()
        .find_map(|e| match e {
            Extension::PreSharedKey(psk) => Some(psk),
            _ => None,
        })
        .expect("捕获里的 PSK 扩展不许在反解时丢掉 —— 丢了它，回放就不再是那条 hello");
    assert_eq!(psk.identities.len(), 1, "捕获里有 1 个 identity");
    assert_eq!(psk.binders.len(), 1, "捕获里有 1 个 binder");
    assert_eq!(
        psk.identities[0].label.len(),
        224,
        "label 是那条 224 字节的会话票据（体长字段 0x00e0；uTLS 的字段名叫 Label）"
    );
    // 逐字节回放：identity 与 binder 的**原字节**都得回来。
    let replay = HandshakeInputs::for_replay(hello).expect("回放输入");
    let again = spec.marshal(&replay).expect("回放").into_bytes();
    assert_eq!(again, hello, "Slack 捕获的反解-再回放该逐字节相同");
}

/// **DumpLargerThanExtensions**：转储里 ClientHello 之后还有帧。
///
/// 两半都判：
/// 1. 把**整条转储**（含尾帧）塞给反解 ⇒ **响亮报错** —— 我们的解析器要求
///    「恰好一条握手消息」，多出来的字节不许被安静吞掉；
/// 2. 摘出 hello 之后的反解-回放逐字节相同。上游那条用 `AllowBluntMimicry: true`
///    才吃得下这条转储里的未知扩展；我们恒 blunt（未知扩展一律 `Opaque` 原样保留），
///    所以同一件事不需要开关，且**扩展条数一条不少**也一并判掉。
#[test]
fn curl_dump_with_trailing_frames_is_rejected_then_replayed_exactly() {
    // ① 整条塞进去必须报错（长度字段对不上剩余字节）。
    let whole = &DUMP[5..];
    assert!(
        ClientHelloSpec::from_bytes(whole).is_err(),
        "带尾帧的转储不许被安静地解析成功 —— 多出来的字节必须响"
    );

    // ② 摘出 hello：反解、回放、逐字节。
    let hello = hello_of(DUMP);
    let spec = ClientHelloSpec::from_bytes(hello).expect("反解");
    assert_eq!(
        spec.extensions.len(),
        wire_ext_count(hello),
        "反解出的扩展条数该与线上一致 —— 未知扩展不许被丢（恒 blunt）"
    );
    let replay = HandshakeInputs::for_replay(hello).expect("回放输入");
    let again = spec.marshal(&replay).expect("回放").into_bytes();
    assert_eq!(again, hello, "curl 捕获的反解-再回放该逐字节相同");
}
